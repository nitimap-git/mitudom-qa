begin;

create table if not exists public.child_quality_results (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2500 and 2700),
  category_code text not null,
  category_name text not null,
  target numeric(5,2) not null check (target between 0 and 100),
  result numeric(5,2) not null check (result between 0 and 100),
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (year, category_code)
);

alter table public.child_quality_results enable row level security;

grant select, insert, update, delete
on public.child_quality_results
to anon;

drop policy if exists "public read child quality results" on public.child_quality_results;
create policy "public read child quality results"
on public.child_quality_results
for select to anon
using (true);

-- ใช้ร่วมกับระบบ Admin ปัจจุบันซึ่งยังไม่ได้ใช้ Supabase Auth
drop policy if exists "temporary anon manage child quality results" on public.child_quality_results;
create policy "temporary anon manage child quality results"
on public.child_quality_results
for all to anon
using (true)
with check (true);

